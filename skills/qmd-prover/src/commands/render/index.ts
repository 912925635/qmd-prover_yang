export interface RenderResult extends OperationResult {
  status: string;
  output?: string;
  graph_svg?: string;
  report?: string;
  render_command?: string;
  summary: CompilationSummary;
  diagnostics?: Diagnostic[];
}

function escapeXml(value: unknown = ''): string {
  const entities: Record<string, string> = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' };
  return String(value).replace(/[&<>"']/g, (character) => entities[character] ?? character);
}

function graphSvg(graph: DependencyGraph): string {
  const layout = layoutGraph(graph, { hasse: true });
  const boxes = new Map(layout.nodes.map((node) => [node.id, node]));
  const defs = '<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M 0 0 L 10 5 L 0 10 z" fill="#9aa5b8"/></marker></defs>';
  const bend = V_GAP / 2;
  const edges = layout.edges.map((edge) => {
    const [start, ...rest] = edge.points;
    const path = edge.back
      ? rest.map((point) => `C ${Math.max(start.x, point.x) + 60} ${start.y}, ${Math.max(start.x, point.x) + 60} ${point.y}, ${point.x} ${point.y}`).join(' ')
      : rest.map((point, index) => {
          const previous = index === 0 ? start : rest[index - 1];
          return `C ${previous.x} ${previous.y + bend}, ${point.x} ${point.y - bend}, ${point.x} ${point.y}`;
        }).join(' ');
    return `<path d="M ${start.x} ${start.y} ${path}" fill="none" stroke="#9aa5b8" stroke-width="1.5"${edge.back ? ' stroke-dasharray="4 3"' : ''} marker-end="url(#arrow)"/>`;
  }).join('');
  const nodes = graph.nodes.map((node) => {
    const position = boxes.get(node.id);
    if (!position) return '';
    const href = `../../${node.file}#${node.id}`;
    const local = node.local_verification?.status ?? 'not-run';
    const global = node.global_verification?.status ?? 'unverified';
    const title = `${node.id}: ${node.title} (local: ${local}; global: ${global})${node.disproof ? ` — ${node.disproof.refutation}` : ''}`;
    return `<a href="${escapeXml(href)}"><g><title>${escapeXml(title)}</title><rect x="${position.x}" y="${position.y}" width="${position.width}" height="${position.height}" rx="8" fill="#fff" stroke="#64748b"/><text x="${position.x + 12}" y="${position.y + 20}" font-family="sans-serif" font-size="13">${escapeXml(node.id)}</text><text x="${position.x + 12}" y="${position.y + 38}" font-family="sans-serif" font-size="11" fill="#586174">${escapeXml(`local ${local}; global ${global}`)}</text></g></a>`;
  }).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${layout.width}" height="${layout.height}" viewBox="0 0 ${layout.width} ${layout.height}" role="img" aria-label="Theorem dependency graph">${defs}${edges}${nodes}</svg>\n`;
}

function statusQmd(compilation: Compilation): string {
  const tableText = (value: unknown): string => String(value ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
  const rows = compilation.manifest.results.map((result) => {
    const local = result.local_verification?.status ?? 'not-run';
    const global = result.global_verification?.status ?? 'unverified';
    return `| @${result.id} | ${local} | ${global} | ${result.disproof ? `${result.disproof.status}: ${tableText(result.disproof.refutation)}` : '—'} | \`${result.file}:${result.line ?? '?'}\` |`;
  }).join('\n');
  const diagnostics = compilation.diagnostics.length
    ? `\n## Diagnostics\n\n${compilation.diagnostics.map((item) => `- **${item.severity} ${item.code}** in \`${item.file ?? '<project>'}:${item.line ?? '?'}\`: ${item.message}`).join('\n')}\n`
    : '';
  return `---\ntitle: "Proof status"\n---\n\nThis page is generated by qmd-prover from the project's semantic QMD. Local verification is conditional on direct dependency statements; global status is computed from the complete dependency closure.\n\n| Result | Local AI | Global | Refutation evidence | Source |\n|---|---|---|---|---|\n${rows || '| — | — | — | — | — |'}\n\n## Dependency graph\n\n![Proof dependency graph](dependencies.svg){fig-alt="A directed graph from results to the definitions and results cited by their proofs."}\n${diagnostics}`;
}

export async function renderProject(root = process.cwd(), options: CompilerOptions & RenderOptions = {}): Promise<RenderResult> {
  root = path.resolve(root);
  const compiled = await compileProject(root, options);
  const context = await verificationContext(compiled);
  const snapshot = await resolveProjectSnapshot(compiled, context.contextHash, options);
  const compilation: Compilation = {
    root,
    config: compiled.config,
    manifest: snapshot.manifest,
    graph: snapshot.graph,
    diagnostics: snapshot.diagnostics,
    summary: {
      files: snapshot.manifest.files.length,
      results: snapshot.manifest.results.length,
      errors: snapshot.diagnostics.filter((item) => item.severity === 'error').length,
      warnings: snapshot.diagnostics.filter((item) => item.severity === 'warning').length
    },
    goals: snapshot.manifest.results.filter((result) => result.origin === 'user'),
    notes: snapshot.notes,
    sourceHashes: compiled.sourceHashes,
    complete: compiled.complete,
    ok: snapshot.diagnostics.every((item) => item.severity !== 'error')
  };
  if (!compilation.ok && options.allowErrors !== true) return {
    schema_version: SCHEMA_VERSION,
    operation: 'render',
    ok: false,
    status: 'blocked',
    summary: compilation.summary,
    diagnostics: compilation.diagnostics,
    artifacts_written: false,
    remediation: 'Repair the diagnostics and rerun render, or explicitly use --allow-errors to generate diagnostic artifacts.'
  };
  const layout = auxLayout(root);
  const output = layout.generated;
  await Promise.all([mkdir(output, { recursive: true }), mkdir(layout.reports, { recursive: true })]);
  await Promise.all([
    atomicWrite(path.join(output, 'proof-status.qmd'), statusQmd(compilation)),
    atomicWrite(path.join(output, 'dependencies.svg'), graphSvg(compilation.graph)),
    atomicJson(layout.reportStatus, { summary: compilation.summary, diagnostics: compilation.diagnostics })
  ]);
  const quartoCmd = quartoCommand(compiled.config);
  const quartoAvailable = await executableAvailable(quartoCmd);
  return {
    schema_version: SCHEMA_VERSION,
    operation: 'render',
    ok: true,
    status: compilation.ok ? 'prepared' : 'prepared-with-errors',
    output: path.relative(root, path.join(output, 'proof-status.qmd')),
    graph_svg: path.relative(root, path.join(output, 'dependencies.svg')),
    report: path.relative(root, layout.reportStatus),
    ...(quartoAvailable ? { render_command: `${quartoCmd} render` } : {}),
    quarto: {
      available: quartoAvailable,
      ...(quartoAvailable ? {} : { remediation: 'Install Quarto, set tools.quarto in config, or set QMD_PROVER_QUARTO, before building final HTML, PDF, or other output.' })
    },
    artifacts_written: true,
    artifacts_trustworthy: compilation.ok,
    summary: compilation.summary,
    diagnostics: compilation.diagnostics
  };
}

